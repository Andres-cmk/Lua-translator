local nested = coroutine.wrap(function()
  local inner = coroutine.wrap(function() coroutine.yield("in1") coroutine.yield("in2") end)
  coroutine.yield(inner()) coroutine.yield(inner()) coroutine.yield("out")
end)
print(nested(), nested(), nested())
